#!/usr/bin/env node
// build-tokens.mjs — emit every engine's view of motion/tokens.json.
//
//   node tools/build-tokens.mjs           # write outputs
//   node tools/build-tokens.mjs --check   # exit 1 if any output is stale (CI / hook)
//
// Outputs
//   motion/dist/tokens.css                      CSS custom properties + @font-face (HyperFrames)
//   motion/dist/tokens.js                       window.TEZPI frozen object (HyperFrames GSAP timelines)
//   remotion/src/motion/tokens.generated.ts     typed const (Remotion)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = join(import.meta.dirname, "..");
const SRC = join(ROOT, "motion", "tokens.json");
const HEADER = "Generated by tools/build-tokens.mjs from motion/tokens.json — do not edit.";

// Strip "$description" (and any "$"-prefixed) doc keys before emitting.
const strip = (v) =>
  Array.isArray(v)
    ? v.map(strip)
    : v && typeof v === "object"
      ? Object.fromEntries(Object.entries(v).filter(([k]) => !k.startsWith("$")).map(([k, x]) => [k, strip(x)]))
      : v;

const tokens = strip(JSON.parse(readFileSync(SRC, "utf8")));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());
const ms = (s) => `${Math.round(s * 1000)}ms`;

// Only eases with a verified CSS equivalent (motion-forge §6). Everything else is GSAP-only.
const CSS_EASE = { none: "linear", "expo.out": "cubic-bezier(0.16, 1, 0.3, 1)" };

function css() {
  const { color, font, type, radius, motion } = tokens;
  const v = [];
  for (const [k, x] of Object.entries(color)) v.push(`  --${kebab(k)}: ${x};`);
  v.push(`  --font-sans: "${font.sans.family}", ${font.sans.fallback};`);
  for (const [name, t] of Object.entries(type)) {
    v.push(`  --type-${name}-size: ${t.size}px;`);
    v.push(`  --type-${name}-weight: ${t.weight};`);
    v.push(`  --type-${name}-tracking: ${t.tracking}em;`);
    v.push(`  --type-${name}-leading: ${t.leading};`);
  }
  for (const [k, x] of Object.entries(radius)) v.push(`  --radius-${kebab(k)}: ${x}px;`);
  for (const [k, x] of Object.entries(motion.blur)) v.push(`  --blur-${kebab(k)}: ${x}px;`);
  v.push(`  --cursor-size: ${motion.cursor.size};`);
  v.push(`  --cursor-size-in-mock: ${motion.cursor.sizeInMock};`);
  v.push(`  --dur-entry-max: ${ms(motion.duration.entryMax)};`);
  for (const [k, g] of Object.entries(motion.ease)) if (CSS_EASE[g]) v.push(`  --ease-${kebab(k)}: ${CSS_EASE[g]};`);

  return `/* ${HEADER} */
@font-face {
  font-family: "${font.sans.family}";
  src: url("./fonts/${font.sans.file}") format("woff2");
  font-weight: ${font.sans.weight};
  font-style: normal;
  font-display: block;
}

:root {
${v.join("\n")}
}
`;
}

function js() {
  return `/* ${HEADER} */
(function () {
  var deepFreeze = function (o) {
    Object.values(o).forEach(function (v) { if (v && typeof v === "object") deepFreeze(v); });
    return Object.freeze(o);
  };
  window.TEZPI = deepFreeze(${JSON.stringify(tokens, null, 2).replace(/\n/g, "\n  ")});
})();
`;
}

function ts() {
  return `// ${HEADER}
export const tokens = ${JSON.stringify(tokens, null, 2)} as const;

export type Tokens = typeof tokens;
export type GsapEase = Tokens["motion"]["ease"][keyof Tokens["motion"]["ease"]];
`;
}

const fontSrc = join(ROOT, "node_modules", "@fontsource-variable", "inter", "files", tokens.font.sans.file);
const outputs = [
  [join(ROOT, "motion", "dist", "tokens.css"), css()],
  [join(ROOT, "motion", "dist", "tokens.js"), js()],
  [join(ROOT, "remotion", "src", "motion", "tokens.generated.ts"), ts()],
  // Remotion loads the same font file the HyperFrames films vendor
  [join(ROOT, "remotion", "public", "fonts", tokens.font.sans.file), existsSync(fontSrc) ? readFileSync(fontSrc) : null],
];

const check = process.argv.includes("--check");
let stale = 0;
for (const [path, body] of outputs) {
  const rel = path.slice(ROOT.length + 1);
  if (body === null) throw new Error(`missing ${fontSrc.slice(ROOT.length + 1)} — run: npm install`);
  if (check) {
    const same = existsSync(path) && Buffer.compare(readFileSync(path), Buffer.from(body)) === 0;
    if (!same) stale++;
    console.log(`${same ? "ok   " : "STALE"} ${rel}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, body);
    console.log(`wrote ${rel}`);
  }
}
if (check && stale) {
  console.error(`\n${stale} token output(s) stale — run: npm run tokens && npm run film:sync`);
  process.exit(1);
}
